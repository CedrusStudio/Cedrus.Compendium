import 'server-only';
import type { ContentBlock, RulebookSection } from '@/domain/rulebook/RulebookTypes';
import { loadAllSections } from '@/persistence/rulebook/rulebookLoader';
import { scoreCatalogEntry, tokenize } from '@/domain/ai-character-generation/selectCatalogEntries';

const MAX_RULEBOOK_FRAGMENTS = 6;
/** Roomy enough that a cost table survives whole; a truncated table is a trap. */
const MAX_FRAGMENT_CHARS = 1_800;

/**
 * Sections worth sending even when the description matches nothing: without
 * them the model has no idea what a rank costs or how many points a character
 * gets, which is how a draft ends up with uniformly excellent statistics.
 */
const ALWAYS_RELEVANT_TERMS = ['tworzenie postaci', 'rozwój', 'koszt', 'punkty', 'ranga'];

function renderBlocks(blocks: readonly ContentBlock[]): string
{
  return blocks
    .map(block => {
      if (block.type === 'paragraph' || block.type === 'heading' || block.type === 'blockquote') return block.content;
      if (block.type === 'list') return block.items.join('\n');
      if (block.type === 'table') {
        return [block.table.headers.join(' | '), ...block.table.rows.map(row => row.join(' | '))].join('\n');
      }
      return '';
    })
    .filter(text => text.length > 0)
    .join('\n');
}

/**
 * Most of the rulebook lives one level down: 17 of 39 sections carry nothing at
 * the top and everything in their subsections, „Punkty Umiejętności" — with the
 * advancement cost tables — among them. Reading only `section.content` sent the
 * model a title and nothing else, which is no use for judging what a rank costs.
 */
function renderSection(section: RulebookSection): string
{
  const body = [
    renderBlocks(section.content),
    ...section.subsections.map(subsection => {
      const subsectionBody = renderBlocks(subsection.content);
      return subsectionBody.length > 0 ? `${subsection.title}\n${subsectionBody}` : '';
    }),
  ]
    .filter(text => text.length > 0)
    .join('\n\n');

  const fragment = `${section.title}\n${body}`.trim();

  return fragment.length <= MAX_FRAGMENT_CHARS
    ? fragment
    : `${fragment.slice(0, MAX_FRAGMENT_CHARS - 1)}…`;
}

/**
 * The rulebook is a large static document, so only the sections that bear on
 * this description travel. Reuses the catalog scorer to keep one notion of
 * "relevant" in the feature — Polish stems and all.
 */
export function loadAiCharacterRulebookFragments(description: string): string[]
{
  let sections: RulebookSection[];
  try {
    sections = loadAllSections();
  } catch {
    // The rulebook is generated by `sync-rulebook` and may simply be absent in
    // a fresh checkout. An unavailable rulebook is a documented context state,
    // not a generation failure.
    return [];
  }

  const queryTokens = tokenize([description, ...ALWAYS_RELEVANT_TERMS].join(' '));

  return sections
    .map(section => ({
      section,
      score: scoreCatalogEntry(
        {
          kind: 'rulebook',
          id: section.slug,
          // Subsection titles are where the specific wording sits — a section
          // called „Punkty Umiejętności" only reveals itself as the cost rules
          // through its „Koszt rozwoju umiejętności" child.
          name: [section.title, ...section.subsections.map(subsection => subsection.title)].join(' '),
          tags: section.tags,
        },
        queryTokens,
      ),
    }))
    .filter(scored => scored.score > 0)
    .sort((left, right) => right.score - left.score)
    .slice(0, MAX_RULEBOOK_FRAGMENTS)
    .map(scored => renderSection(scored.section));
}
